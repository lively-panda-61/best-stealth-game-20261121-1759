// Seeded RNG for THE BRASS CROW: deterministic decoration and guard jitter.
// Mulberry32 — tiny, fast, and the same sequence for the same seed every run.
export function makeRng(seed = 1) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
